package com.example.AccomodationReservationManagementMvc.model;
import jakarta.persistence.*;
import java.time.LocalDate;

@Entity
@Inheritance(strategy = InheritanceType.SINGLE_TABLE)
@DiscriminatorColumn(name = "reservation_type", discriminatorType = DiscriminatorType.STRING)
public abstract class Reservation {
    @Id
    @Column(length = 10, nullable = false, unique = true)
    private String reservationNumber; // Generated by UI (10 characters)[cite: 2]

    @ManyToOne
    @JoinColumn(name = "account_number")
    private Account account; // Account number updated when added[cite: 2]

    private String physicalAddress;
    private String mailingAddress; // If null, UI will know to use physical address[cite: 2]
    private LocalDate startDate;
    private int numberOfNights;
    private int numberOfBeds = 2; // Default 2[cite: 2]
    private int numberOfBedrooms = 1; // Default 1[cite: 2]
    private int numberOfBathrooms = 1; // Default 1[cite: 2]
    private int lodgingSizeSqFt; // integer[cite: 2]
    private Double reservationPrice; // Not set until completed[cite: 2]
    private String status = "DRAFT"; // draft, completed, or cancelled[cite: 2]

    // Constructors, Getters, Setters, and toString() omitted for brevity

    public String getReservationNumber() {
        return reservationNumber;
    }

    public void setReservationNumber(String reservationNumber) {
        this.reservationNumber = reservationNumber;
    }

    public Account getAccount() {
        return account;
    }

    public void setAccount(Account account) {
        this.account = account;
    }

    public String getPhysicalAddress() {
        return physicalAddress;
    }

    public void setPhysicalAddress(String physicalAddress) {
        this.physicalAddress = physicalAddress;
    }

    public String getMailingAddress() {
        return mailingAddress;
    }

    public void setMailingAddress(String mailingAddress) {
        this.mailingAddress = mailingAddress;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public void setStartDate(LocalDate startDate) {
        this.startDate = startDate;
    }

    public int getNumberOfNights() {
        return numberOfNights;
    }

    public void setNumberOfNights(int numberOfNights) {
        this.numberOfNights = numberOfNights;
    }

    public int getNumberOfBeds() {
        return numberOfBeds;
    }

    public void setNumberOfBeds(int numberOfBeds) {
        this.numberOfBeds = numberOfBeds;
    }

    public int getNumberOfBedrooms() {
        return numberOfBedrooms;
    }

    public void setNumberOfBedrooms(int numberOfBedrooms) {
        this.numberOfBedrooms = numberOfBedrooms;
    }

    public int getNumberOfBathrooms() {
        return numberOfBathrooms;
    }

    public void setNumberOfBathrooms(int numberOfBathrooms) {
        this.numberOfBathrooms = numberOfBathrooms;
    }

    public int getLodgingSizeSqFt() {
        return lodgingSizeSqFt;
    }

    public void setLodgingSizeSqFt(int lodgingSizeSqFt) {
        this.lodgingSizeSqFt = lodgingSizeSqFt;
    }

    public Double getReservationPrice() {
        return reservationPrice;
    }

    public void setReservationPrice(Double reservationPrice) {
        this.reservationPrice = reservationPrice;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    @Override
    public String toString() {
        return super.toString();
    }
}